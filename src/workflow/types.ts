import { z } from "zod";

import type { AgentExecutionContext } from "../agents/execution-context.js";

// ---------------------------------------------------------------------------
// Status + signals
// ---------------------------------------------------------------------------

export type WorkflowStatus = "running" | "suspended" | "completed" | "failed" | "cancelled";

export interface SuspendSignal {
  /** Event the workflow resumes on. Ex: "callback:payment.confirmed" or "timeout". */
  resumeOn: string;
  /** TTL in ms — after this, status becomes `failed` with `reason: 'timeout'`. */
  timeoutMs: number;
  /** External token the webhook uses to resume. Generated by engine if omitted. */
  suspendToken?: string;
  /** Context payload exposed to the webhook (ex: payment_intent_id). */
  metadata?: Record<string, unknown>;
}

/**
 * Sentinel key for the resume payload injected into `stepOutputs`.
 * Documented as a constant (not a magic string) per pós-review.
 */
export const RESUME_PAYLOAD_KEY = "__resume__" as const;

// ---------------------------------------------------------------------------
// Step types
// ---------------------------------------------------------------------------

export interface StepContext extends AgentExecutionContext {
  /** Outputs of previously executed steps, keyed by step id. */
  readonly stepOutputs: Record<string, unknown>;

  /**
   * Suspend the workflow. Throws a `WorkflowSuspendError` internally — callers
   * should not catch this; let it bubble back to the engine.
   */
  suspend(signal: SuspendSignal): never;

  /** Tool executor (same signature reasoning engines use). */
  toolExecutor: (name: string, params: unknown, ctx: AgentExecutionContext) => Promise<unknown>;
}

export interface StepResult<T = unknown> {
  output: T;
  durationMs: number;
}

export type StepFn<TInput = unknown, TOutput = unknown> = (
  input: TInput,
  ctx: StepContext,
) => Promise<TOutput>;

export type StepKind = "step" | "branch" | "parallel" | "map";

export interface RetryPolicy {
  maxAttempts: number;
  baseDelayMs: number;
  maxDelayMs?: number;
}

export interface WorkflowStep {
  id: string;
  kind: StepKind;
  execute: StepFn;
  /** Branch predicate — present when `kind === "branch"`. */
  predicate?: (input: unknown, ctx: StepContext) => boolean | Promise<boolean>;
  branches?: { truthy: WorkflowStep[]; falsy: WorkflowStep[] };
  /** Steps executed concurrently when `kind === "parallel"`. */
  parallel?: WorkflowStep[];
  retry?: RetryPolicy;
  timeoutMs?: number;
}

export interface WorkflowDefinition {
  id: string;
  version: number;
  description: string;
  steps: WorkflowStep[];
  /** Optional Zod schema validating the workflow input. */
  inputSchema?: z.ZodTypeAny;
}

// ---------------------------------------------------------------------------
// State (Zod-versioned)
// ---------------------------------------------------------------------------

/**
 * Versioned workflow state schema. `schemaVersion` is required so future
 * migrators can detect older state and upgrade it on resume.
 */
export const WorkflowStateSchemaV1 = z.object({
  schemaVersion: z.literal(1),
  cursor: z.number().int().nonnegative(),
  stepOutputs: z.record(z.string(), z.unknown()),
  branchTrail: z.array(
    z.object({
      stepId: z.string(),
      branch: z.enum(["truthy", "falsy"]),
    }),
  ),
  /** Payload from a resume event (when applicable). Stored explicitly. */
  resumePayload: z.unknown().optional(),
});

export type WorkflowStateV1 = z.infer<typeof WorkflowStateSchemaV1>;

/** Current `WorkflowState` type alias — always the latest version. */
export type WorkflowState = WorkflowStateV1;

/**
 * Placeholder migrator. When schema V2 is introduced, branch on
 * `state.schemaVersion` and upgrade in-place.
 */
export function migrateState(raw: unknown): WorkflowState {
  const parsed = WorkflowStateSchemaV1.safeParse(raw);
  if (parsed.success) return parsed.data;
  throw new Error(
    `Unknown workflow state schema version: ${JSON.stringify(
      (raw as { schemaVersion?: unknown })?.schemaVersion ?? null,
    )}`,
  );
}

export function emptyState(): WorkflowState {
  return {
    schemaVersion: 1,
    cursor: 0,
    stepOutputs: {},
    branchTrail: [],
  };
}

// ---------------------------------------------------------------------------
// Suspend control-flow
// ---------------------------------------------------------------------------

/** Thrown by `ctx.suspend()` to short-circuit step execution. */
export class WorkflowSuspendError extends Error {
  readonly signal: SuspendSignal;
  constructor(signal: SuspendSignal) {
    super(`Workflow suspended waiting for: ${signal.resumeOn}`);
    this.name = "WorkflowSuspendError";
    this.signal = signal;
  }
}
